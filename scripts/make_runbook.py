"""Generate docs/TEST_CALLS.md and the results sheet from the 15 scenario files (so the runbook cannot drift).

Usage: uv run python -m scripts.make_runbook
"""

import csv
from pathlib import Path

from evals.scenario_schema import Scenario, load_scenarios

DOCS = Path(__file__).resolve().parents[1] / "docs"
EXTRAS = [
    ("x1_background_noise", "Background noise", "Play a podcast or TV at normal volume next to you, then book a checkup (any name and a fake number).",
     "It should still understand you, or re-ask politely. It should not book under a wrong phone number."),
    ("x2_silent_caller", "Silent caller", "Click Talk, hear the greeting, then say nothing for about 40 seconds.",
     "The silence ladder: a soft prompt, a check-in, then a goodbye and hang-up (about 10, 20 and 30 seconds)."),
    ("x3_interruption", "Interruption", "Ask 'what are your hours and do you take Delta Dental?' and interrupt mid-answer with 'wait, sorry'.",
     "It should stop within about half a second and respond to what you just said, not finish its sentence."),
]  # fmt: skip


def expectation(s: Scenario) -> list[str]:
    e, out = s.expect, []
    if e.tools_in_order:
        out.append("tools used, in order: " + ", ".join(e.tools_in_order))
    if s.category == "emergency" or "transfer_call" in e.tools_in_order:
        dest = e.tool_args.get("transfer_call", {}).get("destination", "")
        out.append(
            f"transfers right away (turn 1) to {dest}; the web call cannot ring a phone, so look for the announcement"
        )
    if e.forbidden_tools:
        out.append("must NOT use: " + ", ".join(e.forbidden_tools))
    if e.final_state:
        out.append("end state: " + ", ".join(f"{k} = {v}" for k, v in e.final_state.items()))
    out.append("voice style: short replies, numbers spoken as words, AI + recording said first")
    return out


def render(scenarios: list[Scenario]) -> str:
    lines = [
        "# Test-call runbook",
        "",
        "Generated by `scripts/make_runbook.py` from `evals/scenarios/*.yaml`. Do not edit by hand.",
        "",
        "**Before each session:** `make up`, `make api` and `make tunnel` running; `make check-assistant` says IDENTICAL.",
        "Use fake names and fake numbers only (for example 512-555-0142). Each call costs about $0.05 to $0.10.",
        "**After each call:** run `make calls` to see the new call's id, then write pass or fail in `docs/test_calls_results.csv`.",
        "Say the lines naturally, in your own words; the lines below are a guide to the persona and the goal.",
        "",
    ]
    for i, s in enumerate(scenarios, start=1):
        lines += [
            f"## Call {i}: {s.title}",
            "",
            f"*Scenario `{s.id}`, category {s.category}.* **Goal:** {s.goal}",
            "",
            f"**Persona:** {s.persona}",
            "",
            "**Say, in order:**",
            f"1. {s.opening_message}",
        ]
        lines += [f"{n}. {line}" for n, line in enumerate(s.script, start=2)]
        lines += ["", "**Expected:**", *[f"- {x}" for x in expectation(s)], ""]
    lines += ["## Extra calls (not counted in the 15, but each teaches something)", ""]
    for _, title, do, expect in EXTRAS:
        lines += [f"### {title}", f"**Do:** {do}", f"**Expect:** {expect}", ""]
    lines += [
        "## What to write down for every call",
        "- pass or fail against the Expected list, and a one-line note (what felt wrong, any dead air over two seconds)",
        "- whether the greeting said it is an AI and that the call may be recorded (listen for it; one stored transcript lacked the word AI although it was heard correctly)",
        "- latency and cost need no notes: `make bench` reads them from Vapi's report",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    scenarios = load_scenarios()
    (DOCS / "TEST_CALLS.md").write_text(render(scenarios))
    sheet = DOCS / "test_calls_results.csv"
    if not sheet.exists():  # never overwrite results the owner has already entered
        with sheet.open("w", newline="") as f:
            w = csv.writer(f)
            w.writerow(["n", "kind", "scenario_id", "vapi_call_id", "success", "notes"])
            for i, s in enumerate(scenarios, start=1):
                w.writerow([i, "core", s.id, "", "", ""])
            for sid, *_ in EXTRAS:
                w.writerow([sid.split("_")[0], "extra", sid, "", "", ""])
    print(f"wrote {DOCS / 'TEST_CALLS.md'} and {sheet.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
